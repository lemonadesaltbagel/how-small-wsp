"""Episode ledger: one row per run, rebuilt from the run directories (no numbers typed by hand).
  python3 -I scripts/ledger.py            writes notes/episode_ledger.md and notes/episode_ledger.json
Per run: <run>/run_class.json (access level, counts or not, failure label; written by hand when the run is classified),
eval/score.json, eval/holdout_summary.json, audit_summary.json, audit_adjudication.json, rule_gate.jsonl (reviewer
blocks), state.json (turns), the episode log's last status line (passes, Python runs, editor cost)."""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
H = os.path.join(ROOT, "harness")


def j(p, default=None):
    try:
        return json.load(open(p))
    except (OSError, ValueError):
        return default


def gate(run):
    v = {"allow": 0, "block": 0, "unreviewed": 0}
    try:
        for line in open(os.path.join(run, "rule_gate.jsonl")):
            r = json.loads(line)
            k = r.get("verdict")
            v[k if k in v else "unreviewed"] += 1
    except OSError:
        return None
    return v


def row(run):
    rel = os.path.relpath(run, H)
    c = j(os.path.join(run, "run_class.json"), {})
    sc = j(os.path.join(run, "eval", "score.json"), {})
    ho = j(os.path.join(run, "eval", "holdout_summary.json"), {})
    au = j(os.path.join(run, "audit_summary.json"), {})
    adj = j(os.path.join(run, "audit_adjudication.json"), {})
    st = j(os.path.join(run, "state.json"), {})
    acc = lambda k: (ho.get(k) or {}).get("accuracy") if isinstance(ho.get(k), dict) else ho.get(k)
    return {
        "run": rel, "arm": c.get("arm"), "access": c.get("access"), "counts": c.get("counts"),
        "math500": None if (sc.get("math500") or {}).get("error") else sc.get("score"),  # errored scoring is no score
        "scoring_error": bool((sc.get("math500") or {}).get("error")), "failure_label": c.get("failure_label"),
        "holdout": None if not ho or ho.get("skipped") else {k: acc(k) for k in ("mmlupro1k", "gpqa", "ifeval")},
        "audit": {k: au.get(k) for k in ("runs_reviewed", "allowed", "suspicious", "violations", "valid")} if au else None,
        "adjudicated_valid": adj.get("valid") if adj else None,
        "gate": gate(run), "turns": st.get("turn"), "editor_cost_usd": st.get("cost_usd"),
    }


def fmt(x, pct=False):
    if x is None:
        return "—"
    return f"{100 * x:.1f}" if pct else str(x)


def main():
    runs = sorted(glob.glob(os.path.join(H, "runs*", "phase0", "*", "run_class.json")))
    rows = [row(os.path.dirname(p)) for p in runs]
    json.dump(rows, open(os.path.join(ROOT, "notes", "episode_ledger.json"), "w"), indent=1)
    out = ["# Episode ledger (generated by scripts/ledger.py; do not edit by hand)", "",
           "| run | arm | access | counts | MATH-500 % | MMLU-Pro / GPQA / IFEval % | audit allowed/susp./viol. | valid | reviewer blocks | failure label | turns |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ho = r["holdout"]
        hs = " / ".join(fmt(ho[k], True) for k in ("mmlupro1k", "gpqa", "ifeval")) if ho else "—"
        a = r["audit"]
        aus = f"{a['allowed']}/{a['suspicious']}/{a['violations']}" if a else "—"
        valid = r["adjudicated_valid"] if r["adjudicated_valid"] is not None else (a or {}).get("valid")
        g = r["gate"]
        out.append(f"| {r['run']} | {fmt(r['arm'])} | {fmt(r['access'])} | {fmt(r['counts'])} | {fmt(r['math500'], True)} | {hs} | "
                   f"{aus} | {fmt(valid)} | {g['block'] if g else '—'} | {fmt(r['failure_label'])} | {fmt(r['turns'])} |")
    open(os.path.join(ROOT, "notes", "episode_ledger.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
